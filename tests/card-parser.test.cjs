const assert=require('node:assert/strict');
const p=require('../docs/card-parser.js');
const due='2026-11-25';
assert.equal(p.amount('R$ 1.250,90'),125090);
assert.equal(p.amount('1,250.90'),125090);
assert.equal(p.amount('(R$ 20,00)'),-2000);
assert.equal(p.amount('10,00-'),-1000);
assert.throws(()=>p.amount('0,00'));
assert.throws(()=>p.amount('abc'));
assert.equal(p.date('31/12','2026-01-15'),'2025-12-31');
assert.throws(()=>p.date('31/02/2026',due));
assert.equal(p.category('UBER *TRIP'),'Transporte por aplicativo');
assert.equal(p.category('UBER EATS'),'Delivery');
assert.equal(p.category('SUPERMERCADO CONDOR'),'Supermercados');
assert.equal(p.category('Mercado Livre'),'Compras e lojas');
assert.equal(p.category('NETFLIX'),'Assinaturas');
const br=p.fromCsv('Data;Descrição;Valor (R$)\r\n01/11/2026;"UBER;TRIP";25,90\r\n02/11/2026;CONDOR;125,00\r\n03/11/2026;Estorno;-5,00\r\nTOTAL;;145,90',due);
assert.equal(br.items.length,3);assert.equal(br.ignored.length,1);assert.equal(br.items.reduce((s,x)=>s+x.amount_cents,0),14590);
const en=p.fromCsv('date,title,amount\n2026-11-01,"Uber, trip",25.90\n2026-11-02,Netflix,39.90',due);
assert.equal(en.items.length,2);assert.equal(en.items[0].description,'Uber, trip');
const pdf=p.fromLines(['Fatura Novembro','01/11 UBER *TRIP R$ 25,90','02/11 SUPERMERCADO CONDOR 1.125,00','03/11 ESTORNO -10,00','04/11 PAGAMENTO DE FATURA -100,00','TOTAL R$ 1.140,90'],due);
assert.equal(pdf.items.length,4);assert.equal(pdf.ignored.length,2);assert.equal(pdf.items.filter(x=>!p.isPayment(x.description)).reduce((s,x)=>s+x.amount_cents,0),114090);
assert.throws(()=>p.fromCsv('foo,bar\n1,2',due));
console.log('OK: 22 verificações de parser, valores, datas, categorias, CSV e linhas de PDF.');
